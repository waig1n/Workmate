it('keeps uploaded documents idle until explicit start and prevents duplicate submissions',async()=>{
 let finish!:()=>void;
 let status='uploaded';
 vi.mocked(api.get).mockImplementation(resourcePageMock(async path=>path==='/knowledge-bases'?[kb]:path==='/scopes/accessible'?[]:{items:[{id:'doc',filename:'资料.txt',status,chunk_count:0}],total:1}));
 vi.mocked(api.post).mockImplementation(()=>new Promise(resolve=>{finish=()=>{status='pending';resolve({});};}));
 render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><Page/></QueryClientProvider>);
 fireEvent.click(await screen.findByRole('button',{name:/制度库/}));
 expect(await screen.findByText('待启动 · 0 个片段')).toBeVisible();
 expect(api.post).not.toHaveBeenCalled();
 fireEvent.click(screen.getByRole('button',{name:'启动处理'}));
 fireEvent.click(screen.getByRole('button',{name:'启动处理'}));
 expect(api.post).toHaveBeenCalledTimes(1);
 expect(api.post).toHaveBeenCalledWith('/knowledge-bases/kb/documents/doc/start');
 finish();
 expect(await screen.findByText('启动完成：成功 1 个，失败 0 个。')).toBeVisible();
 expect(screen.queryByRole('button',{name:'启动处理'})).toBeNull();
});
it('starts only uploaded documents sequentially and reports partial failures',async()=>{
 const docs=[{id:'a',filename:'a.txt',status:'uploaded'},{id:'b',filename:'b.txt',status:'uploaded'},{id:'c',filename:'c.txt',status:'ready'},{id:'d',filename:'d.txt',status:'pending'}];
 vi.mocked(api.get).mockImplementation(resourcePageMock(async path=>path==='/knowledge-bases'?[kb]:path==='/scopes/accessible'?[]:{items:docs,total:4}));
 let finish!:()=>void;
 vi.mocked(api.post).mockImplementation(path=>path.endsWith('/a/start')?new Promise(resolve=>{finish=()=>{docs[0].status='pending';resolve({});};}):Promise.reject(new Error('服务暂不可用')));
 render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><Page/></QueryClientProvider>);
 fireEvent.click(await screen.findByRole('button',{name:/制度库/}));
 fireEvent.click(await screen.findByRole('button',{name:'启动全部待处理'}));
 expect(api.post).toHaveBeenCalledTimes(1);
 expect(screen.getByRole('button',{name:'启动全部待处理'})).toBeDisabled();
 finish();
 expect(await screen.findByText('启动完成：成功 1 个，失败 1 个。')).toBeVisible();
 expect(api.post).toHaveBeenCalledTimes(2);
 expect(api.post).toHaveBeenLastCalledWith('/knowledge-bases/kb/documents/b/start');
 expect(screen.getByText(/b.txt：服务暂不可用/)).toBeVisible();
});
